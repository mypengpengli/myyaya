import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url), ts = require("typescript");
const code = ts.transpileModule(readFileSync("src/artifacts/media-job-service.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const module = { exports: {} }; new Function("module", "exports", code)(module, module.exports);
const { MediaJobService, MediaRequestUnconfirmed } = module.exports;
const restoredOrder = new MediaJobService({ list: () => [
  { id: "old", createdAt: 1, status: "completed" }, { id: "new", createdAt: 2, status: "running" },
], save() {} }, () => "unused");
assert.deepEqual(restoredOrder.list().map((job) => job.id), ["new", "old"], "restart preserves newest-first task selection before any poll/save");
const rows = new Map(); let ids = 0;
const repository = { list: () => [...rows.values()], save: (job) => rows.set(job.id, { ...job }) };
const jobs = new MediaJobService(repository, () => `job-${++ids}`);
let posts = 0, polls = 0, finishSubmission;
const transport = { submit: async (job) => {
  posts++; assert.equal(rows.get(job.id).status, "submitting", "persist before a possibly billable request");
  return new Promise((resolve) => { finishSubmission = resolve; });
}, poll: async () => { polls++; return { status: "completed", artifactId: "video-result" }; } };
const video = jobs.create({ kind: "video", prompt: "让这只小猫跳舞", parentId: "photo-id" }, "account-a");
const submitting = jobs.submit(video.id, "account-a", transport);
assert.equal(posts, 1); await jobs.submit(video.id, "account-a", transport); assert.equal(posts, 1);
const image = jobs.create({ kind: "image", prompt: "一只小猫" }, "account-a");
assert.throws(() => jobs.create({ kind: "image", prompt: "第三个" }, "account-a"), /两个媒体任务/);
finishSubmission({ remoteId: "remote-video" }); await submitting;
assert.equal(rows.get(video.id).status, "running");
await jobs.submit(video.id, "account-a", transport); assert.equal(posts, 1);
await jobs.poll("account-b", transport); assert.equal(polls, 0, "new credentials cannot poll another account's task");
await jobs.poll("account-a", transport); assert.equal(polls, 1); assert.equal(rows.get(video.id).artifactId, "video-result");
await jobs.poll("account-a", transport); assert.equal(polls, 1, "terminal results stay terminal");
await jobs.submit(image.id, "account-a", { submit: async () => { throw new Error("network disconnected after POST"); }, poll: transport.poll });
assert.equal(rows.get(image.id).status, "unknown");
await jobs.submit(image.id, "account-a", transport); assert.equal(posts, 1, "ambiguous generation cannot be silently resubmitted");
const interrupted = jobs.create({ kind: "edit", prompt: "换成蓝色", parentId: "photo-id" }, "account-a");
const restarted = new MediaJobService(repository, () => `job-${++ids}`);
assert.equal(restarted.list().find((job) => job.id === interrupted.id).status, "unknown", "a process restart cannot duplicate an unconfirmed POST");
assert.equal(restarted.list().find((job) => job.id === video.id).artifactId, "video-result");
const unconfirmed = restarted.create({ kind: "image", prompt: "HTTP failure case" }, "account-a");
await restarted.submit(unconfirmed.id, "account-a", { submit: async () => { throw new MediaRequestUnconfirmed("媒体接口返回 HTTP 504，未取得有效结果；不会自动重复提交"); }, poll: transport.poll });
assert.equal(rows.get(unconfirmed.id).status, "unknown");
assert.match(rows.get(unconfirmed.id).notice, /HTTP 504/);
await restarted.submit(unconfirmed.id, "account-a", transport);
assert.equal(posts, 1, "an explicit HTTP failure still cannot authorize repeating a generation POST");
const badRepository = { list: () => [], save: () => { throw new Error("disk full"); } };
const query = restarted.create({ kind: "video", prompt: "query failure must stay resumable" }, "account-a");
await restarted.submit(query.id, "account-a", { submit: async () => ({ remoteId: "existing-task" }), poll: transport.poll });
await restarted.poll("account-a", { submit: transport.submit, poll: async () => { throw new Error("private provider body"); } });
assert.equal(rows.get(query.id).status, "running");
assert.match(rows.get(query.id).notice, /继续查询/);
assert.equal(rows.get(query.id).notice.includes("private"), false);
const full = new MediaJobService(badRepository, () => "full");
assert.throws(() => full.create({ kind: "video", prompt: "test" }, "account-a"), /disk full/);
console.log("Media jobs: persistence before POST, nonblocking submission, account binding, restart ambiguity, no duplicate billing retry and terminal results: PASS");
